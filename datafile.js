/* ============================================================
   Builds the text of data.js from current values.
   Shared by admin.html (prices & settings) and ops.html (stock
   from released lots), so both always write the same format.
   ============================================================ */
"use strict";

function buildDataFile({ lastUpdated, site, countries, products, benchmarks, fx, generatedBy }) {
  const j = (v) => JSON.stringify(v, null, 2);
  return `/* ============================================================
   Ore Bridge — Product & Market Data
   Generated by ${generatedBy || "admin.html"} on ${new Date().toISOString().slice(0, 10)}
   Product prices are indicative FOB, USD per metric tonne.
   Each product's \`history\` holds its real recorded prices by date.
   Each reference price in BENCHMARKS carries \`asOf\` and \`source\`.
   Easiest way to edit: admin.html (prices) and ops.html (stock).
   ============================================================ */

const LAST_UPDATED = ${JSON.stringify(lastUpdated)};

const SITE = ${j(site)};

const COUNTRIES = ${j(countries || [])};

const PRODUCTS = ${j(products)};

const BENCHMARKS = ${j(benchmarks)};

const USD_TO_EGP = ${Number(fx)};
`;
}

/* Copies of the loaded products, without the retired `trend` field. */
function cloneProducts(list) {
  return list.map((p) => {
    const { trend, ...rest } = p;
    return { ...rest, history: Array.isArray(p.history) ? p.history.map((h) => ({ ...h })) : [] };
  });
}

function downloadText(text, filename, type) {
  const url = URL.createObjectURL(new Blob([text], { type: type || "text/plain" }));
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1500);
}
